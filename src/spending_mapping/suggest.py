def suggest(name: str, categories: list[Category]) -> str | None:
    by_name = {category.name: category.pk for category in categories}
    upper = name.upper()
    for keywords, category_name in RULES:
        for keyword in keywords:
            if keyword.upper() in upper:
                return by_name.get(category_name)
    return None
